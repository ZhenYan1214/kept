// Generates src/generated/contracts.ts from the Foundry build output and deployment files,
// so the web app always uses the exact ABIs and addresses of the contracts it talks to.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contracts = join(here, "..", "..", "contracts");
const outFile = join(here, "..", "src", "generated", "contracts.ts");

const names = {
  registryAbi: "EligibilityRegistry",
  factoryAbi: "KeptFactory",
  fundAbi: "ReliefFund",
  ledgerAbi: "CustodyLedger",
  voiceAbi: "VoiceModule",
  programsAbi: "AidPrograms",
  tokenAbi: "MockTWD",
  semaphoreAbi: "ISemaphore",
  semaphoreGroupsAbi: "ISemaphoreGroups",
};

if (!existsSync(join(contracts, "out"))) {
  console.log("contracts/out not found; keeping existing src/generated/contracts.ts");
  process.exit(0);
}

let src = "// AUTO-GENERATED by scripts/sync-contracts.mjs — do not edit.\n\n";
for (const [exportName, contract] of Object.entries(names)) {
  const artifact = JSON.parse(readFileSync(join(contracts, "out", `${contract}.sol`, `${contract}.json`), "utf8"));
  src += `export const ${exportName} = ${JSON.stringify(artifact.abi)} as const;\n\n`;
}

const deploymentsDir = join(contracts, "deployments");
const deployments = {};
if (existsSync(deploymentsDir)) {
  for (const f of readdirSync(deploymentsDir).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(readFileSync(join(deploymentsDir, f), "utf8"));
    deployments[d.chainId] = d;
  }
}
src += `export type Deployment = {
  chainId: number;
  deployBlock: number;
  owner: \`0x\${string}\`;
  semaphore: \`0x\${string}\`;
  token: \`0x\${string}\`;
  registry: \`0x\${string}\`;
  factory: \`0x\${string}\`;
  ledger: \`0x\${string}\`;
  voice: \`0x\${string}\`;
  programs: \`0x\${string}\`;
};\n\n`;
src += `export const deployments: Record<number, Deployment> = ${JSON.stringify(deployments, null, 2)};\n`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, src);
console.log(`Wrote ${outFile} (${Object.keys(deployments).length} deployment(s))`);
